"use client";

import { useFleetStore } from "@/store/useFleetStore";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { AlertTriangle, Bell, Shield, Activity, Route, Fuel, CheckCircle2 } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";

export default function AlertsPage() {
  const { alerts, vehicles, markAlertRead } = useFleetStore();

  const getSeverityColor = (severity: string) => {
    switch(severity) {
      case 'Critical': return 'bg-destructive/10 text-destructive border-destructive/20';
      case 'Warning': return 'bg-amber-500/10 text-amber-500 border-amber-500/20';
      default: return 'bg-blue-500/10 text-blue-500 border-blue-500/20';
    }
  };

  const getTypeIcon = (type: string) => {
    switch(type) {
      case 'Overspeeding': return <Activity className="h-4 w-4" />;
      case 'Geofence': return <Shield className="h-4 w-4" />;
      case 'Fuel Event': return <Fuel className="h-4 w-4" />;
      default: return <Bell className="h-4 w-4" />;
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row justify-between gap-4 items-start sm:items-center">
        <div>
          <h1 className="text-3xl font-bold tracking-tight">Alerts</h1>
          <p className="text-muted-foreground">Monitor and manage fleet notifications.</p>
        </div>
      </div>
      
      <Card>
        <CardHeader>
          <CardTitle>Recent Alerts</CardTitle>
          <CardDescription>Real-time notifications generated by the telemetry engine</CardDescription>
        </CardHeader>
        <CardContent>
          <div className="space-y-4">
            {alerts.length === 0 ? (
              <div className="flex flex-col items-center justify-center py-12 text-muted-foreground">
                <CheckCircle2 className="h-12 w-12 mb-4 text-green-500/50" />
                <p>All clear! No active alerts in the system.</p>
              </div>
            ) : (
              alerts.map((alert) => {
                const vehicle = vehicles.find(v => v.id === alert.vehicleId);
                
                return (
                  <div key={alert.id} className={`flex items-start justify-between p-4 rounded-lg border ${alert.isRead ? 'bg-muted/30 border-transparent' : 'bg-card border-border shadow-sm'}`}>
                    <div className="flex items-start gap-4">
                      <div className={`mt-0.5 w-8 h-8 rounded-full flex items-center justify-center border ${getSeverityColor(alert.severity)}`}>
                        {getTypeIcon(alert.type)}
                      </div>
                      <div className="space-y-1">
                        <div className="flex items-center gap-2">
                          <p className={`font-medium ${alert.isRead ? 'text-muted-foreground' : 'text-foreground'}`}>
                            {vehicle?.name || 'Unknown Vehicle'}
                          </p>
                          <Badge variant="outline" className={`text-[10px] h-4 px-1.5 ${getSeverityColor(alert.severity)}`}>
                            {alert.type}
                          </Badge>
                        </div>
                        <p className={`text-sm ${alert.isRead ? 'text-muted-foreground' : 'text-foreground'}`}>{alert.message}</p>
                        <p className="text-xs text-muted-foreground">{new Date(alert.timestamp).toLocaleString()}</p>
                      </div>
                    </div>
                    {!alert.isRead && (
                      <Button variant="ghost" size="sm" onClick={() => markAlertRead(alert.id)}>
                        Mark Read
                      </Button>
                    )}
                  </div>
                );
              })
            )}
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
